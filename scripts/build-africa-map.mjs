// Generates src/data/africa-map.ts: SVG paths for every African country,
// projected once at build time so the site ships no mapping libraries.
// Run with: npm run build:map
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature, merge } from "topojson-client";
import { presimplify, simplify, quantile } from "topojson-simplify";
import { geoAzimuthalEqualArea, geoPath } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-50m.json"), "utf8"));

// ISO 3166 numeric codes for African countries and territories
const AFRICA = ["012","024","204","072","854","108","132","120","140","148","174","178","180","384","262","818","226","232","748","231","266","270","288","324","624","404","426","430","434","450","454","466","478","480","504","508","516","562","566","646","678","686","690","694","706","710","728","729","834","768","788","800","732","894","716"];
// Participating countries: ISO code -> slug used in src/data/countries.ts
const PARTICIPATING = { "024":"angola","072":"botswana","108":"burundi","180":"drc","231":"ethiopia","404":"kenya","454":"malawi","508":"mozambique","646":"rwanda","678":"sao-tome","894":"zambia" };

let t = presimplify(topo);
t = simplify(t, quantile(t, 0.35));
const geoms = t.objects.countries.geometries;

// Somaliland is drawn as part of Somalia, following World Bank / UN cartographic practice
const somalia = {
  type: "Feature", id: "706", properties: { name: "Somalia" },
  geometry: merge(t, geoms.filter((g) => g.id === "706" || g.properties.name === "Somaliland")),
};
let feats = feature(t, t.objects.countries).features.filter((f) => AFRICA.includes(f.id) && f.id !== "706");
feats.push(somalia);

// Drop sub-Antarctic outliers (e.g. Prince Edward Islands) so the map frames the continent
feats = feats.map((f) => {
  if (f.geometry.type !== "MultiPolygon") return f;
  const polys = f.geometry.coordinates.filter((p) => p[0].some(([, lat]) => lat > -40));
  return { ...f, geometry: { type: "MultiPolygon", coordinates: polys } };
});

const W = 600, H = 660;
const collection = { type: "FeatureCollection", features: feats };
const projection = geoAzimuthalEqualArea().rotate([-18, -2]).fitExtent([[12, 12], [W - 12, H - 12]], collection);
const path = geoPath(projection).digits(1);

const shapes = feats
  .map((f) => {
    const [cx, cy] = path.centroid(f);
    const slug = PARTICIPATING[f.id];
    const d = path(f);
    return d ? (slug ? [d, slug, +cx.toFixed(1), +cy.toFixed(1)] : [d]) : null;
  })
  .filter(Boolean)
  .sort((a, b) => (a.length > 1 ? 1 : 0) - (b.length > 1 ? 1 : 0)); // participating last, drawn on top

const b = path.bounds(collection);
const viewBox = [Math.floor(b[0][0]) - 8, Math.floor(b[0][1]) - 8, Math.ceil(b[1][0] - b[0][0]) + 16, Math.ceil(b[1][1] - b[0][1]) + 16].join(" ");

const out = `// Generated by scripts/build-africa-map.mjs. Do not edit by hand; run \`npm run build:map\`.
// Source: Natural Earth 1:50m via world-atlas, azimuthal equal-area projection.

/** A non-participating country is [path]; a participating one is [path, slug, centroidX, centroidY]. */
export type MapShape = readonly [string] | readonly [string, string, number, number];

export const MAP_VIEWBOX = "${viewBox}";

export const AFRICA_SHAPES: readonly MapShape[] = ${JSON.stringify(shapes)};
`;
writeFileSync(new URL("../src/data/africa-map.ts", import.meta.url), out);
console.log(`Wrote ${shapes.length} shapes, viewBox ${viewBox}`);
